package com.weiguangplus.network

import android.content.Context
import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import androidx.datastore.preferences.core.stringPreferencesKey
import androidx.datastore.preferences.preferencesDataStore
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import okhttp3.Interceptor
import okhttp3.Response

/**
 * DataStore?????Context?????
 */
internal val Context.authDataStore: DataStore<Preferences> by preferencesDataStore(
    name = "auth_preferences"
)

/**
 * ??Token?DataStore????
 */
private val ACCESS_TOKEN_KEY = stringPreferencesKey("access_token")

/**
 * ???????
 *
 * ??????HTTP??????
 * ?????????AccessToken?????????
 *
 * ?????2026-07-23??
 * - intercept() ????? runBlocking????? @Volatile ????
 * - ???? OkHttp ??????????? ANR
 * - Token ???????????? DataStore
 *
 * @param context Android????????DataStore?
 */
class AuthInterceptor(
    private val context: Context
) : Interceptor {

    /**
     * ????Token???@Volatile?????????
     * ??????DataStore???????????????OkHttp??
     */
    @Volatile
    private var cachedToken: String? = null

    init {
        cachedToken = runBlocking {
            context.authDataStore.data.first()[ACCESS_TOKEN_KEY]
        }
    }

    /**
     * ?????HTTP??
     *
     * ???????Token?????????????
     */
    override fun intercept(chain: Interceptor.Chain): Response {
        val originalRequest = chain.request()
        val accessToken = cachedToken

        if (accessToken.isNullOrBlank()) {
            return chain.proceed(originalRequest)
        }

        val authenticatedRequest = originalRequest.newBuilder()
            .header("Authorization", "Bearer $accessToken")
            .build()

        return chain.proceed(authenticatedRequest)
    }

    /**
     * ???????????Token??????
     */
    fun updateCachedToken(token: String?) {
        cachedToken = token
    }

    companion object {
        /**
         * ?????????AccessToken?????
         */
        fun setAccessToken(context: Context, token: String) {
            runBlocking {
                context.authDataStore.updateData { preferences ->
                    preferences.toMutablePreferences().also { it[ACCESS_TOKEN_KEY] = token }
                }
            }
        }

        /**
         * ????????????AccessToken
         */
        fun clearAccessToken(context: Context) {
            runBlocking {
                context.authDataStore.updateData { preferences ->
                    preferences.toMutablePreferences().apply { remove(ACCESS_TOKEN_KEY) }
                }
            }
        }

        /**
         * ????????????????AccessToken
         */
        fun hasValidToken(context: Context): Boolean {
            return runBlocking {
                val token = context.authDataStore.data.first()[ACCESS_TOKEN_KEY]
                !token.isNullOrBlank()
            }
        }
    }
}
